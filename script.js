function loadPreferences() {
  try {
    const saved = JSON.parse(window.localStorage.getItem(PREFERENCES_KEY));
    if (!saved || typeof saved !== "object") return;
    if (["ru", "uz"].includes(saved.language)) appState.language = saved.language;
    if (["reading", "meaning", "mixed"].includes(saved.quizMode)) appState.quizMode = saved.quizMode;
    if ([15, 30, 60, "all"].includes(saved.quizCount)) appState.quizCount = saved.quizCount;
  } catch {
    // The app also works with unavailable or corrupt browser storage.
  }
}

function savePreferences() {
  try {
    const { language, quizMode, quizCount } = appState;
    window.localStorage.setItem(PREFERENCES_KEY, JSON.stringify({ language, quizMode, quizCount }));
  } catch {
    // Browser privacy settings must not interrupt a study session.
  }
}

