function handleKeydown(e) {
  if (e.isComposing || e.altKey || e.ctrlKey || e.metaKey) return;
  const modalOpen = !DOM.detailModal.hidden;
  if (modalOpen && e.key === "Tab") {
    const controls = [DOM.detailModalContent, ...Array.from(DOM.detailModalContent.querySelectorAll(
      'button:not(:disabled), [tabindex="0"]',
    )).filter((el) => el.getClientRects().length > 0)];
    const first = controls[0];
    const last = controls[controls.length - 1];
    if (!controls.includes(document.activeElement)) {
      e.preventDefault();
      (e.shiftKey ? last : first)?.focus({ preventScroll: true });
    } else if (e.shiftKey && document.activeElement === first) {
      e.preventDefault();
      last?.focus({ preventScroll: true });
    } else if (!e.shiftKey && document.activeElement === last) {
      e.preventDefault();
      first?.focus({ preventScroll: true });
    }
    return;
  }
  if (e.repeat) return;
  if (modalOpen) {
    if (e.key === "Escape" && appState.isReferenceModal) {
      e.preventDefault();
      closeModal();
    } else if (e.key === "Enter" && !appState.isReferenceModal) {
      e.preventDefault();
      nextQuestion();
    }
    return;
  }
  if (e.target?.closest('input, textarea, select, [contenteditable="true"]')) return;
  if (appState.currentScreen === "quiz") {
    const keyMap = { a: 0, b: 1, c: 2, d: 3, 1: 0, 2: 1, 3: 2, 4: 3 };
    const index = keyMap[e.key.toLowerCase()];
    const button = DOM.optionsGrid.querySelectorAll(".option-btn")[index];
    if (button && !button.disabled) {
      e.preventDefault();
      button.click();
    }
  }
}

function toggleLanguage() {
  if (isLanguageSwitchLocked()) return;

  appState.language = appState.language === "ru" ? "uz" : "ru";
  savePreferences();
  updateUI();

  if (appState.currentScreen === "reference") {
    generateKanjiGrid();
  }

  if (DOM.detailModal.classList.contains("active")) {
    const currentChar = DOM.modalKanji.textContent;
    const idx = kanjiIndexMap.get(currentChar);
    if (idx !== undefined) {
      showKanjiDetail(idx, appState.isReferenceModal);
    }
  }

  if (appState.currentScreen === "results") {
    showResults();
  }
}

