function sanitizeRichText(input) {
  if (!input) return "";

  const template = document.createElement("template");
  template.innerHTML = input;
  const allowedTags = new Set(["RUBY", "RT", "RB", "RP", "BR"]);

  const sanitizeNode = (node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      return document.createTextNode(node.textContent || "");
    }

    if (node.nodeType !== Node.ELEMENT_NODE) {
      return document.createDocumentFragment();
    }

    if (node.tagName === "RUBY") {
      const base = Array.from(node.childNodes)
        .filter((child) => !["RT", "RP"].includes(child.nodeName))
        .map((child) => child.textContent || "")
        .join("");
      const reading = node.querySelector("rt")?.textContent || "";
      const safeRuby = document.createElement("template");
      safeRuby.innerHTML = renderFurigana(base, reading);
      return safeRuby.content;
    }

    if (!allowedTags.has(node.tagName)) {
      const fragment = document.createDocumentFragment();
      node.childNodes.forEach((child) => {
        fragment.appendChild(sanitizeNode(child));
      });
      return fragment;
    }

    const safeElement = document.createElement(node.tagName.toLowerCase());
    node.childNodes.forEach((child) => {
      safeElement.appendChild(sanitizeNode(child));
    });
    return safeElement;
  };

  const wrapper = document.createElement("div");
  template.content.childNodes.forEach((node) => {
    wrapper.appendChild(sanitizeNode(node));
  });
  return wrapper.innerHTML;
}

